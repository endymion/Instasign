#!/usr/bin/env node
/**
 * Generate gitignored mqtt_iot_secrets.h for the matrix usermod from certs/matrix/.
 * Emits DER byte arrays (Tasmota mbedtls builds often omit PEM parse).
 */
import { readFile, writeFile, mkdir, mkdtemp } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const CERTS = path.join(ROOT, "certs");
const OUT_DIR = path.resolve(
  ROOT,
  "../../wled/usermods/matrix_display/secrets",
);
const OUT = path.join(OUT_DIR, "mqtt_iot_secrets.h");

function opensslDer(args, outPath) {
  const res = spawnSync("openssl", args, { stdio: "inherit" });
  if (res.status !== 0) {
    throw new Error(`openssl ${args.join(" ")} failed`);
  }
  return outPath;
}

function toCByteArray(name, buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 12) {
    const chunk = [...buf.subarray(i, i + 12)]
      .map((b) => `0x${b.toString(16).padStart(2, "0")}`)
      .join(", ");
    lines.push(`  ${chunk},`);
  }
  return `static const unsigned char ${name}[] = {\n${lines.join("\n")}\n};\nstatic const size_t ${name}_LEN = ${buf.length};\n`;
}

async function main() {
  const endpoint = (await readFile(path.join(CERTS, "endpoint.txt"), "utf8")).trim();
  const topic = (await readFile(path.join(CERTS, "topic.txt"), "utf8")).trim();
  const caPem = path.join(CERTS, "AmazonRootCA1.pem");
  const certPem = path.join(CERTS, "matrix", "certificate.pem.crt");
  const keyPem = path.join(CERTS, "matrix", "private.pem.key");

  const dir = await mkdtemp(path.join(tmpdir(), "instasign-der-"));
  const caDer = path.join(dir, "ca.der");
  const certDer = path.join(dir, "cert.der");
  const keyDer = path.join(dir, "key.der");

  opensslDer(["x509", "-in", caPem, "-outform", "DER", "-out", caDer], caDer);
  opensslDer(["x509", "-in", certPem, "-outform", "DER", "-out", certDer], certDer);
  opensslDer(["rsa", "-in", keyPem, "-outform", "DER", "-out", keyDer], keyDer);

  const ca = await readFile(caDer);
  const cert = await readFile(certDer);
  const key = await readFile(keyDer);

  await mkdir(OUT_DIR, { recursive: true });

  const header = `#pragma once
// AUTO-GENERATED by infra/mqtt/scripts/generate-firmware-secrets.mjs — DO NOT COMMIT
// Instasign matrix device credentials for AWS IoT Core (DER; PEM parse unavailable)

#ifndef MATRIX_IOT_SECRETS_PRESENT
#define MATRIX_IOT_SECRETS_PRESENT 1
#endif

static const char MQTT_IOT_ENDPOINT[] = "${endpoint}";
static const int MQTT_IOT_PORT = 8883;
static const char MQTT_IOT_CLIENT_ID[] = "instasign-matrix";
static const char MQTT_IOT_TOPIC[] = "${topic}";

${toCByteArray("MQTT_IOT_ROOT_CA_DER", ca)}
${toCByteArray("MQTT_IOT_DEVICE_CERT_DER", cert)}
${toCByteArray("MQTT_IOT_PRIVATE_KEY_DER", key)}
`;

  await writeFile(OUT, header, "utf8");
  console.log("Wrote", OUT, `(ca=${ca.length} cert=${cert.length} key=${key.length} DER bytes)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
