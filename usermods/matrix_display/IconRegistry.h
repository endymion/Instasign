inline String normalizeIconName(const String& name) {
  String out;
  out.reserve(name.length());
  for (unsigned i = 0; i < name.length(); i++) {
    char c = name.charAt(i);
    if (c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '-' || c == '_') continue;
    if (c >= 'A' && c <= 'Z') c = c - 'A' + 'a';
    out += c;
  }
  return out;
}

